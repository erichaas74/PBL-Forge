/**
 * The authored inquiry bank.
 *
 * Items bind to a **concept** and a **probe**, never to a workstation id, so one item runs in every
 * instrument declaring that probe. Grade bands are an explicit set — an AP student never receives a
 * grade-7 item, and a grade-7 student never receives an AP one. Phase is authored rather than
 * derived from array position.
 *
 * Selection never pads a short bank with generated filler; a gap surfaces in the coverage report
 * instead. `assertValidInquiryBank()` keeps every item pointing at a real concept and a probe that
 * concept actually admits.
 */

const A: readonly InstructionLevel[] = ['grade-7', 'grade-8', 'high-school', 'ap-biology'];
const L: readonly InstructionLevel[] = ['grade-7', 'grade-8'];
const U: readonly InstructionLevel[] = ['grade-8', 'high-school', 'ap-biology'];
const X: readonly InstructionLevel[] = ['high-school', 'ap-biology'];
const G7: readonly InstructionLevel[] = ['grade-7'];

function c(
  id: string,
  conceptId: ConceptId,
  requiresProbe: ProbeId,
  gradeBands: readonly InstructionLevel[],
  phase: SimulationPhase,
  prompt: string,
  options: readonly [string, string, string],
  correctIndex: 0 | 1 | 2,
  explanation: string,
  hint?: string,
): ChoiceItem {
  const ids = ['a', 'b', 'c'] as const;
  return {
    kind: 'choice',
    id,
    conceptId,
    requiresProbe,
    gradeBands,
    phase,
    hint,
    source: 'registry',
    prompt,
    options: options.map((label, index) => ({ id: ids[index], label })),
    correctOptionId: ids[correctIndex],
    explanation,
  };
}

