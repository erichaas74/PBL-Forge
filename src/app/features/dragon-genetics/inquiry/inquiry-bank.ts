const BY_ID = new Map(DRAGON_INQUIRY_BANK.map((item) => [item.id, item]));

export function inquiryItem(id: string | null | undefined): InquiryItem | null {
  return id ? (BY_ID.get(id) ?? null) : null;
}

export function itemsForConcept(conceptId: ConceptId): readonly InquiryItem[] {
  return DRAGON_INQUIRY_BANK.filter((item) => item.conceptId === conceptId);
}

/**
 * Concepts with no authored item at a given band. This is the coverage report that replaces
 * generated filler: a gap is reported rather than papered over.
 */
export function uncoveredConcepts(level: InstructionLevel): readonly ConceptId[] {
  const covered = new Set(
    DRAGON_INQUIRY_BANK.filter((item) => item.gradeBands.includes(level)).map(
      (item) => item.conceptId,
    ),
  );
  return DRAGON_CONCEPTS.filter(
    (concept) => concept.gradeBands.includes(level) && !covered.has(concept.id),
  ).map((concept) => concept.id);
}

export function assertValidInquiryBank(): void {
  const seen = new Set<string>();
  for (const item of DRAGON_INQUIRY_BANK) {
    if (seen.has(item.id)) throw new Error(`Duplicate inquiry item ${item.id}.`);
    seen.add(item.id);
    const concept = dragonConcept(item.conceptId);
    if (!concept) throw new Error(`Item ${item.id} targets unknown concept ${item.conceptId}.`);
    if (!concept.probes.includes(item.requiresProbe)) {
      throw new Error(
        `Item ${item.id} requires probe ${item.requiresProbe}, which concept ${concept.id} does not admit.`,
      );
    }
    if (!instrumentsWithProbe(item.requiresProbe).length) {
      throw new Error(`Item ${item.id} requires probe ${item.requiresProbe}, which no instrument declares.`);
    }
    if (!item.gradeBands.length) throw new Error(`Item ${item.id} declares no grade band.`);
    for (const band of item.gradeBands) {
      if (!concept.gradeBands.includes(band)) {
        throw new Error(`Item ${item.id} targets band ${band} outside concept ${concept.id}.`);
      }
    }
    if (item.kind === 'choice') {
      if (item.options.length < 2) throw new Error(`Item ${item.id} needs at least two options.`);
      if (!item.options.some((option) => option.id === item.correctOptionId)) {
        throw new Error(`Item ${item.id} has no option matching its correct id.`);
      }
    }
  }
}

assertValidInquiryBank();
